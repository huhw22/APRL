#!/usr/bin/env python3
"""Render the APRL 4 m SASE exact-unit-weight card and an inspectable plan."""

from __future__ import annotations

import json
import hashlib
import math
import os
from pathlib import Path


C = 299_792_458.0
HC_EV_M = 1.239_841_984e-6
FRINGE_CUTOFF = 1.0e-9


def need(name: str) -> str:
    value = os.environ.get(name, "")
    if not value:
        raise SystemExit("missing environment variable: " + name)
    return value


def f(name: str) -> float:
    return float(need(name))


def i(name: str) -> int:
    return int(need(name))


def quoted(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def round_up(value: int, alignment: int) -> int:
    return ((value + alignment - 1) // alignment) * alignment


def make_card(*, case: dict[str, object], particle_file: Path,
              run_dir: Path, values: dict[str, object]) -> str:
    return f"""# Auto-generated by scripts/generate_campaign.py; do not edit this copy.
units:
  length: m
  time: s

runtime:
  mode: throughput
  resource_monitor:
    enabled: true
    progress_interval_steps: {values['resource_progress']}
    calibration_steps: {values['resource_calibration']}
    memory_safety_factor: 1.25
    time_safety_factor: 1.25
  # Bound both the complete shutdown path and, more tightly, MPI_Finalize.
  # The latter lets the batch wrapper reclaim a finalize-only runtime hang
  # after every required output has already been closed.
  shutdown_watchdog:
    enabled: true
    timeout_seconds: 600
    finalize_timeout_seconds: 60

output:
  overwrite: false
  manifest: {quoted(run_dir / 'run-manifest.yaml')}

mesh:
  field_solver: cowan-z
  current_filter: none
  cells: [{values['nx']}, {values['ny']}, auto]
  cell_size: [{values['dx']:.17g}, {values['dy']:.17g}, {case['dz_box_m']:.17g}]
  center: [0.0, 0.0, 0.0]
  duration: {values['duration']:.17g}
  boost_gamma: {values['boost_gamma']:.17g}
  particle_steps_per_undulator_period: {values['particle_steps']}
  maximum_particle_substeps: {values['maximum_substeps']}
  longitudinal:
    mode: observation-bounded
    lower_guard_cells: {case['lower_guard_cells']}
    upper_guard_cells: {case['upper_guard_cells']}
    self_field_padding_rms: {values['self_field_padding_rms']:.17g}
    ballistic_time_safety_factor: {values['ballistic_safety']:.17g}
    alignment_cells: {values['alignment']}

radiation_resolution:
  enabled: true
  maximum_photon_energy_eV: {values['photon_ceiling_eV']:.17g}
  warning_grid_points_per_wavelength: 8.0
  warning_maxwell_samples_per_cycle: 8.0
  warning_detector_samples_per_cycle: 8.0

boundary:
  type: cpml
  cells: [{values['cpml_xy']}, {values['cpml_xy']}, {case['cpml_z_cells']}]
  polynomial_order: 3.0
  target_reflection: 1.0e-8
  kappa_max: 8.0
  alpha_fraction: 0.0

# Deliberately enabled in this case. A zero automatic RMS padding keeps
# the observation-bounded z size while the relativistic-Poisson solve still
# initializes the complete non-CPML interval and enforces discrete Gauss law.
initial_self_field:
  enabled: true
  model: relativistic-poisson
  relative_tolerance: {values['initial_field_tolerance']:.17g}
  maximum_iterations: {values['initial_field_maximum_iterations']}

beam:
  reference:
    initial_center_z: {values['initial_z']:.17g}
  input:
    type: hdf5
    file: {quoted(particle_file)}
    electrons: {values['electrons']:.17g}
    position_offset: [0.0, 0.0, 0.0]

sources:
  incident_waves: []
  magnetic_elements:
    - type: planar-undulator
      characteristic: true
      strength_parameter: {values['undulator_k']:.17g}
      period: {values['undulator_period_m']:.17g}
      periods: {values['undulator_periods']}
      entrance_z: 0.0
      polarization_angle_rad: 1.5707963267948966
      gaussian_fringe: true
      fringe_relative_cutoff: {FRINGE_CUTOFF:.17g}

detectors:
  enabled: true
  directory: {quoted(run_dir / 'detectors')}
  field_planes: []
  particle_planes:
    - name: entry-particles
      z: {values['entry_z']:.17g}
      buffer_records: 65536
      compression: {values['compression']}
    - name: exit-particles
      z: {values['exit_z']:.17g}
      buffer_records: 65536
      compression: {values['compression']}

stop:
  mode: after-last-element

trajectory:
  enabled: false

energy_ledger:
  enabled: true
  directory: {quoted(run_dir / 'ledger')}
  filename: energy-ledger.h5
  sample_interval_steps: {values['ledger_interval']}
  buffer_records: 128
  compression: {values['compression']}
  warning_relative_tolerance: {values['residual_warning']:.17g}
"""


def main() -> None:
    work = Path(need("CAMPAIGN_WORK_DIR")).expanduser().resolve()
    gamma = f("GAMMA_LAB")
    sigma_gamma = f("SIGMA_GAMMA")
    strength = f("UNDULATOR_K")
    period = f("UNDULATOR_PERIOD_M")
    periods = i("UNDULATOR_PERIODS")
    if periods != 170:
        raise SystemExit("this comparison is fixed to 170 undulator periods")
    undulator_length = period * periods
    if not math.isclose(undulator_length, 3.978, rel_tol=0.0, abs_tol=1.0e-12):
        raise SystemExit("170 periods must produce the requested 3.978 m length")

    boost_gamma = gamma / math.sqrt(1.0 + 0.5 * strength * strength)
    gamma_beta = math.sqrt(boost_gamma - 1.0) * math.sqrt(boost_gamma + 1.0)
    boost_beta = gamma_beta / boost_gamma
    beta_e = math.sqrt(1.0 - 1.0 / (gamma * gamma))
    lambda_r = period * (1.0 + 0.5 * strength * strength) / (2.0 * gamma * gamma)
    resonance_eV = HC_EV_M / lambda_r
    requested_length = f("BUNCH_LENGTH_M")
    wavelength_cells = int(math.floor(requested_length / lambda_r + 0.5))
    effective_length = wavelength_cells * lambda_r
    harmonics = i("SASE_HARMONICS")
    members = 2 * (harmonics + 1)
    beamlets = i("BEAMLETS_PER_WAVELENGTH")
    if beamlets != 768:
        raise SystemExit("this exact-unit-weight test is fixed to B=768")
    dz_lab = f("DZ_LAB_M")
    if not math.isclose(dz_lab, 1.35e-9, rel_tol=2.0e-14):
        raise SystemExit("this test is fixed to 1.35 nm laboratory dz")

    electrons = f("ELECTRONS")
    target_reference_electrons = f("TARGET_REFERENCE_ELECTRONS")
    requested_weight = f("MACROPARTICLE_WEIGHT")
    if requested_weight != 1.0:
        raise SystemExit("MACROPARTICLE_WEIGHT must be exactly 1")
    nx, ny = i("MESH_NX"), i("MESH_NY")
    dx, dy = f("MESH_DX_M"), f("MESH_DY_M")
    cpml_xy = i("CPML_CELLS_XY")
    cpml_z = i("CPML_CELLS_Z")
    alignment = i("AUTO_ALIGNMENT_CELLS")
    ranks = i("NODES") * i("TASKS_PER_NODE")
    if alignment % ranks != 0:
        raise SystemExit("AUTO_ALIGNMENT_CELLS must be divisible by total MPI ranks")

    initial_z = f("INITIAL_CENTER_Z_M")
    entry_z = f("ENTRY_PARTICLE_Z_M")
    exit_z = f("EXIT_PARTICLE_Z_M")
    ku = 2.0 * math.pi / period
    fringe = math.sqrt(-2.0 * math.log(FRINGE_CUTOFF)) / ku
    interaction_start = -fringe
    interaction_end = undulator_length + fringe
    if not initial_z + 0.5 * effective_length < entry_z < interaction_start:
        raise SystemExit("entry plane/initial bunch must be upstream of the entrance fringe")
    if not exit_z > interaction_end:
        raise SystemExit("exit plane must be downstream of the undulator fringe")

    self_field_padding_rms = f("AUTO_SELF_FIELD_PADDING_RMS")
    if self_field_padding_rms < 0.0:
        raise SystemExit("AUTO_SELF_FIELD_PADDING_RMS must be nonnegative")
    lower_guard = i("AUTO_LOWER_GUARD_CELLS")
    upper_guard = i("AUTO_UPPER_GUARD_CELLS")
    if min(lower_guard, upper_guard) < 2:
        raise SystemExit("automatic longitudinal guards must each be at least two cells")
    initial_field_tolerance = f("INITIAL_FIELD_TOLERANCE")
    initial_field_maximum_iterations = i("INITIAL_FIELD_MAXIMUM_ITERATIONS")
    if not 0.0 < initial_field_tolerance < 1.0:
        raise SystemExit("INITIAL_FIELD_TOLERANCE must lie between zero and one")
    if initial_field_maximum_iterations < 1:
        raise SystemExit("INITIAL_FIELD_MAXIMUM_ITERATIONS must be positive")

    values: dict[str, object] = {
        "nx": nx, "ny": ny, "dx": dx, "dy": dy,
        "duration": f("MESH_DURATION_S"), "boost_gamma": boost_gamma,
        "particle_steps": i("PARTICLE_STEPS_PER_PERIOD"),
        "maximum_substeps": i("MAXIMUM_PARTICLE_SUBSTEPS"),
        "self_field_padding_rms": self_field_padding_rms,
        "initial_field_tolerance": initial_field_tolerance,
        "initial_field_maximum_iterations": initial_field_maximum_iterations,
        "ballistic_safety": f("AUTO_BALLISTIC_SAFETY"),
        "alignment": alignment, "cpml_xy": cpml_xy,
        "photon_ceiling_eV": 1.25 * resonance_eV,
        "initial_z": initial_z, "entry_z": entry_z, "exit_z": exit_z,
        "electrons": electrons, "undulator_k": strength,
        "undulator_period_m": period, "undulator_periods": periods,
        "compression": i("HDF5_COMPRESSION"),
        "ledger_interval": i("LEDGER_INTERVAL_STEPS"),
        "residual_warning": f("ENERGY_RESIDUAL_WARNING"),
        "resource_progress": i("RESOURCE_PROGRESS_INTERVAL_STEPS"),
        "resource_calibration": i("RESOURCE_CALIBRATION_STEPS"),
    }

    case_specs = (("dz1p35-B0768", dz_lab, beamlets),)
    cases: list[dict[str, object]] = []
    input_specs: dict[int, dict[str, object]] = {}
    # Pre-run resource estimate.  APRL resolves the exact envelope from every
    # generated particle; here we conservatively sample the two ends of the
    # top-hat at gamma +/- 5 sigma.  In particular, include the complete
    # start-to-stop ballistic world tube, not only the initial support and the
    # forward light ray.
    head_lab = initial_z + 0.5 * effective_length
    target_distance = exit_z - head_lab
    radiation_advance = target_distance / (boost_gamma + gamma_beta)
    gamma_samples = (
        max(1.0 + 1.0e-12, gamma - 5.0 * sigma_gamma),
        gamma,
        gamma + 5.0 * sigma_gamma,
    )
    sampled_particles: list[tuple[float, float, float]] = []
    for sampled_gamma in gamma_samples:
        sampled_beta = math.sqrt(1.0 - 1.0 / (sampled_gamma * sampled_gamma))
        denominator = 1.0 - boost_beta * sampled_beta
        beta_box_z = (sampled_beta - boost_beta) / denominator
        for relative_lab_z in (-effective_length, 0.0):
            start_box_z = relative_lab_z / (boost_gamma * denominator)
            event_lab_z = head_lab + relative_lab_z / denominator
            lab_advance_per_box_s = (
                boost_gamma * C * (boost_beta + beta_box_z)
            )
            stop_time = (exit_z - event_lab_z) / lab_advance_per_box_s
            sampled_particles.append((start_box_z, beta_box_z, stop_time))
    ballistic_stop_time = max(item[2] for item in sampled_particles)
    planned_ballistic_time = ballistic_stop_time * float(values["ballistic_safety"])
    start_positions = [item[0] for item in sampled_particles]
    finish_positions = [
        item[0] + item[1] * C * planned_ballistic_time
        for item in sampled_particles
    ]
    initial_minimum = min(start_positions)
    initial_maximum = max(start_positions)
    initial_mean = 0.5 * (initial_minimum + initial_maximum)
    initial_rms = (initial_maximum - initial_minimum) / math.sqrt(12.0)
    ballistic_minimum = min(start_positions + finish_positions)
    ballistic_maximum = max(start_positions + finish_positions)
    radiation_upper = initial_maximum + radiation_advance

    for tag, dz_lab, beamlets in case_specs:
        dz_box = dz_lab * boost_gamma
        if min(dx, dy) < dz_box:
            raise SystemExit(f"{tag}: cowan-z requires dx,dy >= boosted dz")
        records = wavelength_cells * beamlets * members
        if records % ranks != 0:
            raise SystemExit(f"{tag}: record count must divide evenly across {ranks} ranks")
        weight = electrons / records
        electrons_per_beamlet = electrons / (wavelength_cells * beamlets)
        if weight != requested_weight:
            raise SystemExit(
                f"{tag}: exact unit weight failed: electrons={electrons:.17g}, "
                f"records={records}, weight={weight:.17g}"
            )
        self_field_lower = initial_mean - self_field_padding_rms * initial_rms
        self_field_upper = initial_mean + self_field_padding_rms * initial_rms
        content_lower = min(initial_minimum, ballistic_minimum, self_field_lower)
        content_upper = max(
            initial_maximum, ballistic_maximum, radiation_upper,
            self_field_upper,
        )
        physical_extent_estimate = (
            content_upper - content_lower
            + (lower_guard + upper_guard) * dz_box
        )
        physical_cells_estimate = math.ceil(physical_extent_estimate / dz_box)
        total_cells_estimate = round_up(physical_cells_estimate + 2 * cpml_z, alignment)
        particle_file = work / "inputs" / f"sase-B{beamlets:04d}.h5"
        run_dir = work / "runs" / tag
        case = {
            "tag": tag,
            "dz_lab_m": dz_lab,
            "dz_box_m": dz_box,
            "beamlets_per_wavelength": beamlets,
            "macroparticles": records,
            "electrons_per_macroparticle": weight,
            "electrons_per_beamlet": electrons_per_beamlet,
            "lower_guard_cells": lower_guard,
            "upper_guard_cells": upper_guard,
            "lower_guard_box_m": lower_guard * dz_box,
            "upper_guard_box_m": upper_guard * dz_box,
            "cpml_z_cells": cpml_z,
            "cpml_z_box_m": cpml_z * dz_box,
            "particle_file": str(particle_file),
            "config": str(work / "configs" / f"{tag}.yaml"),
            "run_dir": str(run_dir),
            "estimated_auto_nz": total_cells_estimate,
            "estimated_lab_equivalent_box_m": total_cells_estimate * dz_lab,
            "grid_points_per_1p25_band_minimum": (
                (lambda_r / 1.25) * boost_gamma * (1.0 + boost_beta) /
                dz_box
            ),
        }
        cases.append(case)
        input_specs.setdefault(beamlets, {
            "beamlets_per_wavelength": beamlets,
            "path": str(particle_file),
            "macroparticles": records,
            "electrons_per_macroparticle": weight,
            "electrons_per_beamlet": electrons_per_beamlet,
        })
        atomic_write(Path(case["config"]), make_card(
            case=case, particle_file=particle_file, run_dir=run_dir,
            values=values,
        ))

    if len(cases) != 1 or int(cases[0]["macroparticles"]) != int(electrons):
        raise SystemExit("unit-weight campaign must have one record per electron")

    numerics = {
        "field_solver": "cowan-z",
        "current_filter": "none",
        "mesh_nx": nx,
        "mesh_ny": ny,
        "mesh_dx_m": dx,
        "mesh_dy_m": dy,
        "mesh_duration_s": values["duration"],
        "cpml_xy_cells_per_face": cpml_xy,
        "cpml_z_cells_per_face": cpml_z,
        "initial_self_field_enabled": True,
        "initial_self_field_model": "relativistic-poisson",
        "initial_self_field_relative_tolerance": values["initial_field_tolerance"],
        "initial_self_field_maximum_iterations": values["initial_field_maximum_iterations"],
        "auto_self_field_padding_rms": self_field_padding_rms,
        "particle_steps_per_undulator_period": values["particle_steps"],
        "maximum_particle_substeps": values["maximum_substeps"],
        "auto_lower_guard_cells": lower_guard,
        "auto_upper_guard_cells": upper_guard,
        "auto_ballistic_safety_factor": values["ballistic_safety"],
        "auto_alignment_cells": alignment,
        "initial_center_z_m": initial_z,
        "entry_particle_plane_z_m": entry_z,
        "exit_particle_plane_z_m": exit_z,
        "energy_ledger_interval_steps": values["ledger_interval"],
    }
    plan = {
        "purpose": "4 m APRL SASE exact-unit-weight test at dz_lab=1.35 nm",
        "scope": "single exact-weight-one case; no K=0 baseline; box-clipped Gauss-consistent initial field",
        "required_aprl_commit": "3bc0ae8 or later",
        "cases": cases,
        "inputs": list(input_specs.values()),
        "beam": {
            "requested_length_m": requested_length,
            "effective_length_m": effective_length,
            "longitudinal_distribution": "uniform top-hat",
            "electrons": electrons,
            "reference_electrons": target_reference_electrons,
            "relative_charge_change_from_reference": (
                electrons / target_reference_electrons - 1.0
            ),
            "gamma": gamma,
            "sigma_gamma": sigma_gamma,
            "sigma_x_m": f("SIGMA_X_M"),
            "sigma_y_m": f("SIGMA_Y_M"),
            "mean_current_A": electrons * 1.602_176_634e-19 * beta_e * C / effective_length,
        },
        "shot_noise": {
            "model": "Fawley multibeamlet multiharmonic quiet start",
            "seed": i("RANDOM_SEED"),
            "harmonics": harmonics,
            "wavelength_cells": wavelength_cells,
            "exact_unit_macro_weight": True,
        },
        "undulator": {
            "K": strength, "period_m": period, "periods": periods,
            "length_m": undulator_length, "interaction_fringe_m": fringe,
        },
        "theory": {
            "resonant_wavelength_m": lambda_r,
            "resonant_photon_energy_eV": resonance_eV,
            "boost_gamma": boost_gamma,
            "total_resonant_slippage_m": periods * lambda_r,
        },
        "automatic_longitudinal_estimate": {
            "model": "top-hat endpoints at mean gamma plus/minus 5 sigma",
            "initial_bounds_box_m": [initial_minimum, initial_maximum],
            "initial_mean_box_m": initial_mean,
            "initial_rms_box_m": initial_rms,
            "self_field_padding_rms": self_field_padding_rms,
            "ballistic_bounds_box_m": [ballistic_minimum, ballistic_maximum],
            "ballistic_stop_time_s": ballistic_stop_time,
            "planned_ballistic_time_s": planned_ballistic_time,
            "forward_radiation_advance_box_m": radiation_advance,
            "note": "estimate only; APRL resolves exact Nz from generated particles and writes it to each manifest",
        },
        "numerics": numerics,
        "mpi": {"nodes": i("NODES"), "tasks_per_node": i("TASKS_PER_NODE"), "ranks": ranks},
        "reference_case": {
            "tag": need("REFERENCE_TAG"),
            "electrons": f("REFERENCE_ELECTRONS"),
            "macroparticles": i("REFERENCE_MACROPARTICLES"),
            "peak_abs_relative_residual": f("REFERENCE_PEAK_RESIDUAL"),
            "final_field_energy_J": f("REFERENCE_FINAL_FIELD_ENERGY_J"),
            "elapsed_s": f("REFERENCE_ELAPSED_S"),
            "peak_rss_total_mib": f("REFERENCE_PEAK_RSS_MIB"),
            "note": "completed dz1p35-B0192 run; reporting baseline only",
        },
    }
    portable_cases = [
        {
            key: value for key, value in case.items()
            if key not in {"particle_file", "config", "run_dir"}
        }
        for case in cases
    ]
    identity_payload = {
        "schema": "aprl-sase4m-weight1-campaign-v1",
        "scope": plan["scope"],
        "cases": portable_cases,
        "beam": plan["beam"],
        "shot_noise": plan["shot_noise"],
        "undulator": plan["undulator"],
        "theory": plan["theory"],
        "numerics": numerics,
        "mpi": plan["mpi"],
    }
    plan["campaign_fingerprint"] = hashlib.sha256(
        json.dumps(
            identity_payload, sort_keys=True, separators=(",", ":"),
            ensure_ascii=True, allow_nan=False,
        ).encode("utf-8")
    ).hexdigest()
    metadata = work / "metadata"
    atomic_write(metadata / "campaign-plan.json",
                 json.dumps(plan, ensure_ascii=False, indent=2) + "\n")

    rows = [
        "# APRL 4 m SASE exact-unit-weight plan", "",
        f"- Portable campaign fingerprint: `{plan['campaign_fingerprint']}`.",
        f"- Undulator: `{periods} x {period:.8g} m = {undulator_length:.8g} m`.",
        f"- Resonance: `{lambda_r:.12g} m`; total slippage `{periods * lambda_r:.8g} m`.",
        f"- Top-hat input: requested `{requested_length:.8g} m`, effective `{effective_length:.8g} m`, mean current `{plan['beam']['mean_current_A']:.8g} A`.",
        f"- Exact weight one requires `{int(electrons):,}` records/electrons; charge and current are `{100.0 * (electrons / target_reference_electrons - 1.0):.5g}%` above the 18,000,000-electron reference.",
        "- Initial Poisson field is **enabled** with `self_field_padding_rms=0`; it initializes the resolved physical box without adding a `+/-4 sigma` extension.",
        "- The 64/128 z guards and 20-cell z CPML are the same physical fine-grid settings used by the completed 1.35 nm cases.",
        "- Electrons/beamlet are only 8; the generator will warn that Fawley's small-phase approximation is marginal. This is an extreme numerical-noise test, not a certified SASE ensemble.",
        "", "| case | dz lab (nm) | z guards (cells) | z guards in box (um) | z-CPML cells | records | electrons/macro | electrons/beamlet | estimated auto Nz | estimated lab-equivalent box (um) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for case in cases:
        rows.append(
            f"| {case['tag']} | {float(case['dz_lab_m']) * 1e9:.3f} | "
            f"{int(case['lower_guard_cells'])}/{int(case['upper_guard_cells'])} | "
            f"{float(case['lower_guard_box_m']) * 1e6:.6g}/"
            f"{float(case['upper_guard_box_m']) * 1e6:.6g} | "
            f"{int(case['cpml_z_cells'])} | "
            f"{int(case['macroparticles']):,} | "
            f"{float(case['electrons_per_macroparticle']):.8g} | "
            f"{float(case['electrons_per_beamlet']):.8g} | "
            f"{int(case['estimated_auto_nz']):,} | "
            f"{float(case['estimated_lab_equivalent_box_m']) * 1e6:.5g} |"
        )
    rows += [
        "", "The auto-Nz figures are pre-run estimates. The resolved values in each `run-manifest.yaml` are authoritative.",
    ]
    atomic_write(metadata / "campaign-plan.md", "\n".join(rows) + "\n")

    print(f"Rendered exact-unit-weight campaign in {work}")
    print(f"lambda_r={lambda_r:.12g} m boost_gamma={boost_gamma:.12g} undulator={undulator_length:.6g} m")
    print(f"top-hat requested/effective={requested_length:.12g}/{effective_length:.12g} m cells={wavelength_cells}")
    for case in cases:
        print(
            f"  {case['tag']}: dz_lab={float(case['dz_lab_m']) * 1e9:.3f} nm "
            f"records={int(case['macroparticles']):,} "
            f"e/macro={float(case['electrons_per_macroparticle']):.9g} "
            f"e/beamlet={float(case['electrons_per_beamlet']):.9g} "
            f"estimated_auto_nz={int(case['estimated_auto_nz']):,}"
        )


if __name__ == "__main__":
    main()
